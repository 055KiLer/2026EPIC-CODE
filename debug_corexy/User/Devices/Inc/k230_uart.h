/**
 * @file    k230_uart.h
 * @brief   视觉帧解析（Devices 层，纯字节流解析器）
 * @note    对端 = 视觉上位机 **ROCK 5C**（2026-09-22 由庐山派 K230 改型；`k230_*` 是历史命名，
 *          协议与上位机型号无关）。上位机侧的串口/系统要求见电控文档 §4.1"上位机侧要求"表
 *          帧：AA 55 | 状态 | 类别 形状 hasQR **数量** X_L X_H Y_L Y_H | 校验，共 12 字节
 *          状态 1=有目标 0=无目标；X/Y 小端 int16，单位 0.1mm
 *          ★ 2026-09-30 口径：**类别 ID 1~6** 放在原"颜色"字节里（上位机不再拆颜色×形状）。
 *          ★ 2026-10-01 口径：原"形状"字节 = **形状 0~3**（0 = 默认夹持方案；1 = 立方体、
 *            2 = 12面体、3 = 六棱柱 = 三种特调），**不参与分类**，只选夹持方案
 *          ★ 2026-10-10 口径：原**第 2 个"保留"字节（下标 6）= 数量位**，范围 0~255，
 *            = **本帧里托盘上物块的总数**（含当前目标那一个；只数托盘区内，不含投放区/
 *            料盒/爪里那一个）。**每帧都要填、状态 00 的帧也要照周期发**（数量 0 的帧
 *            是"空了"的唯一凭据，见 Config/sort_config.h 的数量复核一节）。
 *            两个判据都由它出：①发车帧数量 vs 到账帧数量差 1 ⇒ 本件真投放
 *            ②到账帧数量 0 ⇒ 托盘空了 ⇒ 空盘静默窗（等人补货）
 *         hasQR 保持解析但电控不使用（货物表面二维码属模拟污渍）
 *          本模块只做 字节流 -> 帧，串口取字节与目标缓存归 App/vision_task
 */
#ifndef __K230_UART_H
#define __K230_UART_H

#include "main.h"

typedef struct {
    uint8_t valid;    /* 1 = 当前帧有有效目标 */
    uint8_t category; /* 货物类别 ID 1~6（帧的原颜色字节）：决定进哪个盒 */
    uint8_t shape;    /* 货物形状 0~3（帧的原形状字节）：0=默认方案、1~3=特调（不参与分类） */
    uint8_t has_qr;   /* 电控忽略 */
    uint8_t count;    /* ★ 数量位（下标 6，2026-10-10）：本帧托盘上物块总数 0~255。
                         校验通过的帧**都填**（含状态 00 的无目标帧）——空盘的"0"靠它 */
    float   x_mm;
    float   y_mm;
} K230_Target_t;

typedef enum {
    K230_EV_NONE = 0, /* 字节已消费，未构成完整帧（或校验失败被丢弃） */
    K230_EV_TARGET,   /* 一帧有效目标（frame_out 已填充） */
    K230_EV_EMPTY     /* 一帧"无目标" */
} K230_Event_e;

/**
 * @brief  喂 1 字节给解析器
 * @param  frame_out EV_TARGET 时输出目标，可为 NULL
 * @retval 本字节触发的事件类型
 */
K230_Event_e K230_FeedByte(uint8_t byte, K230_Target_t *frame_out);

#endif